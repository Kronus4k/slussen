USE ROLE ACCOUNTADMIN;

CREATE STORAGE INTEGRATION IF NOT EXISTS SLUSSEN_S3_INT
  TYPE = EXTERNAL_STAGE
  STORAGE_PROVIDER = 'S3'
  ENABLED = TRUE
  STORAGE_AWS_ROLE_ARN = '<integration_role_arn>'
  STORAGE_ALLOWED_LOCATIONS = ('s3://slussen-lake-qwer/landing/olist/', 's3://slussen-lake-qwer/validated/')
  COMMENT = 'Read access to the Slussen lake via IAM role slussen-snowflake-integration';

GRANT USAGE ON INTEGRATION SLUSSEN_S3_INT TO ROLE DATA_ENGINEER;
GRANT USAGE ON INTEGRATION SLUSSEN_S3_INT TO ROLE LOADER_ROLE;

DESC INTEGRATION SLUSSEN_S3_INT;