USE ROLE SYSADMIN;

GRANT CREATE FILE FORMAT ON SCHEMA ECOM_DB.AUDIT TO ROLE AUDIT_RW;
GRANT CREATE STAGE ON SCHEMA ECOM_DB.AUDIT TO ROLE AUDIT_RW;
GRANT CREATE PIPE ON SCHEMA ECOM_DB.AUDIT TO ROLE AUDIT_RW;

USE ROLE DATA_ENGINEER;
USE SECONDARY ROLES NONE;
SHOW GRANTS TO ROLE AUDIT_RW;
SELECT "privilege", "name"
FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()))
WHERE "granted_on" = 'SCHEMA'
ORDER BY 1;