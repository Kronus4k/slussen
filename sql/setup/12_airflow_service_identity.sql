USE ROLE USERADMIN;

CREATE ROLE IF NOT EXISTS ORCHESTRATOR_ROLE
  COMMENT = 'Airflow: reads Bronze, writes Audit results';

CREATE USER IF NOT EXISTS SVC_AIRFLOW
  TYPE = SERVICE
  DEFAULT_ROLE = ORCHESTRATOR_ROLE
  DEFAULT_WAREHOUSE = TRANSFORM_WH
  DEFAULT_SECONDARY_ROLES = ()
  COMMENT = 'Airflow service user, key-pair authentication only';

USE ROLE SECURITYADMIN;

GRANT ROLE BRONZE_READ TO ROLE ORCHESTRATOR_ROLE;
GRANT ROLE AUDIT_RW TO ROLE ORCHESTRATOR_ROLE;
GRANT ROLE WH_TRANSFORM_USAGE TO ROLE ORCHESTRATOR_ROLE;
GRANT ROLE ORCHESTRATOR_ROLE TO ROLE SYSADMIN;
GRANT ROLE ORCHESTRATOR_ROLE TO USER SVC_AIRFLOW;

USE ROLE ACCOUNTADMIN;
USE WAREHOUSE TRANSFORM_WH;

SHOW GRANTS TO ROLE ORCHESTRATOR_ROLE;
SET orchestrator_has = (SELECT LISTAGG("name", ', ') WITHIN GROUP (ORDER BY "name") FROM TABLE(RESULT_SCAN(LAST_QUERY_ID())));

SHOW GRANTS OF ROLE ORCHESTRATOR_ROLE;
SET orchestrator_granted_to = (SELECT LISTAGG("grantee_name", ', ') WITHIN GROUP (ORDER BY "grantee_name") FROM TABLE(RESULT_SCAN(LAST_QUERY_ID())));

SHOW USERS LIKE 'SVC_AIRFLOW';
SELECT
  $orchestrator_has AS orchestrator_has,
  $orchestrator_granted_to AS orchestrator_granted_to,
  "type",
  "default_role",
  "default_warehouse",
  "default_secondary_roles",
  "has_rsa_public_key"
FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()));

USE ROLE DATA_ENGINEER;