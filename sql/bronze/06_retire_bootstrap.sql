USE ROLE DATA_ENGINEER;
USE SECONDARY ROLES NONE;
USE WAREHOUSE LOAD_WH;
USE SCHEMA ECOM_DB.BRONZE;

DROP TABLE IF EXISTS OLIST_CUSTOMERS_BOOTSTRAP;
DROP TABLE IF EXISTS OLIST_GEOLOCATION_BOOTSTRAP;
DROP TABLE IF EXISTS OLIST_ORDERS_BOOTSTRAP;
DROP TABLE IF EXISTS OLIST_ORDER_ITEMS_BOOTSTRAP;
DROP TABLE IF EXISTS OLIST_ORDER_PAYMENTS_BOOTSTRAP;
DROP TABLE IF EXISTS OLIST_ORDER_REVIEWS_BOOTSTRAP;
DROP TABLE IF EXISTS OLIST_PRODUCTS_BOOTSTRAP;
DROP TABLE IF EXISTS OLIST_PRODUCT_CATEGORY_NAME_TRANSLATION_BOOTSTRAP;
DROP TABLE IF EXISTS OLIST_SELLERS_BOOTSTRAP;

DROP STAGE IF EXISTS STG_OLIST_LANDING;
DROP FILE FORMAT IF EXISTS FF_OLIST_CSV;

SELECT
    (SELECT COUNT(*) FROM ECOM_DB.INFORMATION_SCHEMA.TABLES
      WHERE TABLE_SCHEMA = 'BRONZE' AND ENDSWITH(TABLE_NAME, '_BOOTSTRAP')) AS bootstrap_tables_left,
    (SELECT COUNT(*) FROM ECOM_DB.INFORMATION_SCHEMA.STAGES
      WHERE STAGE_SCHEMA = 'BRONZE' AND STAGE_NAME = 'STG_OLIST_LANDING') AS bootstrap_stage_left,
    (SELECT COUNT(*) FROM ECOM_DB.INFORMATION_SCHEMA.TABLES
      WHERE TABLE_SCHEMA = 'BRONZE' AND TABLE_TYPE = 'BASE TABLE') AS bronze_tables;