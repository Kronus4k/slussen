USE ROLE DATA_ENGINEER;
USE SECONDARY ROLES NONE;
USE WAREHOUSE TRANSFORM_WH;
USE SCHEMA ECOM_DB.BRONZE;

WITH checks AS (
    SELECT 'orders' AS table_name,
        (SELECT COUNT(*) FROM OLIST_ORDERS) AS typed_rows,
        (SELECT COUNT(*) FROM OLIST_ORDERS_BOOTSTRAP) AS bootstrap_rows,
        (SELECT TO_VARCHAR(MAX(order_purchase_timestamp), 'YYYY-MM-DD HH24:MI:SS') FROM OLIST_ORDERS) AS typed_value,
        (SELECT MAX(order_purchase_timestamp) FROM OLIST_ORDERS_BOOTSTRAP) AS bootstrap_value
    UNION ALL
    SELECT 'order_items',
        (SELECT COUNT(*) FROM OLIST_ORDER_ITEMS),
        (SELECT COUNT(*) FROM OLIST_ORDER_ITEMS_BOOTSTRAP),
        (SELECT TO_VARCHAR(SUM(price)) FROM OLIST_ORDER_ITEMS),
        (SELECT TO_VARCHAR(SUM(TRY_TO_NUMBER(price, 10, 2))) FROM OLIST_ORDER_ITEMS_BOOTSTRAP)
    UNION ALL
    SELECT 'order_payments',
        (SELECT COUNT(*) FROM OLIST_ORDER_PAYMENTS),
        (SELECT COUNT(*) FROM OLIST_ORDER_PAYMENTS_BOOTSTRAP),
        (SELECT TO_VARCHAR(SUM(payment_value)) FROM OLIST_ORDER_PAYMENTS),
        (SELECT TO_VARCHAR(SUM(TRY_TO_NUMBER(payment_value, 10, 2))) FROM OLIST_ORDER_PAYMENTS_BOOTSTRAP)
    UNION ALL
    SELECT 'order_reviews',
        (SELECT COUNT(*) FROM OLIST_ORDER_REVIEWS),
        (SELECT COUNT(*) FROM OLIST_ORDER_REVIEWS_BOOTSTRAP),
        (SELECT TO_VARCHAR(COUNT(review_comment_message)) FROM OLIST_ORDER_REVIEWS),
        (SELECT TO_VARCHAR(COUNT(review_comment_message)) FROM OLIST_ORDER_REVIEWS_BOOTSTRAP)
    UNION ALL
    SELECT 'customers',
        (SELECT COUNT(*) FROM OLIST_CUSTOMERS),
        (SELECT COUNT(*) FROM OLIST_CUSTOMERS_BOOTSTRAP),
        (SELECT TO_VARCHAR(COUNT_IF(customer_zip_code_prefix LIKE '0%')) FROM OLIST_CUSTOMERS),
        (SELECT TO_VARCHAR(COUNT_IF(customer_zip_code_prefix LIKE '0%')) FROM OLIST_CUSTOMERS_BOOTSTRAP)
    UNION ALL
    SELECT 'sellers',
        (SELECT COUNT(*) FROM OLIST_SELLERS),
        (SELECT COUNT(*) FROM OLIST_SELLERS_BOOTSTRAP),
        (SELECT TO_VARCHAR(COUNT_IF(seller_zip_code_prefix LIKE '0%')) FROM OLIST_SELLERS),
        (SELECT TO_VARCHAR(COUNT_IF(seller_zip_code_prefix LIKE '0%')) FROM OLIST_SELLERS_BOOTSTRAP)
    UNION ALL
    SELECT 'products',
        (SELECT COUNT(*) FROM OLIST_PRODUCTS),
        (SELECT COUNT(*) FROM OLIST_PRODUCTS_BOOTSTRAP),
        (SELECT TO_VARCHAR(SUM(product_weight_g)) FROM OLIST_PRODUCTS),
        (SELECT TO_VARCHAR(SUM(TRY_TO_NUMBER(product_weight_g))) FROM OLIST_PRODUCTS_BOOTSTRAP)
    UNION ALL
    SELECT 'geolocation',
        (SELECT COUNT(*) FROM OLIST_GEOLOCATION),
        (SELECT COUNT(*) FROM OLIST_GEOLOCATION_BOOTSTRAP),
        (SELECT TO_VARCHAR(SUM(geolocation_lat)) FROM OLIST_GEOLOCATION),
        (SELECT TO_VARCHAR(SUM(TRY_TO_NUMBER(geolocation_lat, 24, 20))) FROM OLIST_GEOLOCATION_BOOTSTRAP)
    UNION ALL
    SELECT 'product_category_name_translation',
        (SELECT COUNT(*) FROM OLIST_PRODUCT_CATEGORY_NAME_TRANSLATION),
        (SELECT COUNT(*) FROM OLIST_PRODUCT_CATEGORY_NAME_TRANSLATION_BOOTSTRAP),
        (SELECT TO_VARCHAR(COUNT(DISTINCT product_category_name_english)) FROM OLIST_PRODUCT_CATEGORY_NAME_TRANSLATION),
        (SELECT TO_VARCHAR(COUNT(DISTINCT product_category_name_english)) FROM OLIST_PRODUCT_CATEGORY_NAME_TRANSLATION_BOOTSTRAP)
)
SELECT table_name, typed_rows, bootstrap_rows, typed_rows = bootstrap_rows AS rows_match,
       typed_value, bootstrap_value, typed_value = bootstrap_value AS values_match
FROM checks
ORDER BY table_name;