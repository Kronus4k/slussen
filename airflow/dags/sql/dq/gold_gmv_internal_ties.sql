WITH o AS (
    SELECT SUM(gmv) AS gmv FROM ECOM_DB.GOLD.FCT_ORDERS
), c AS (
    SELECT 'items' AS name, (SELECT SUM(gmv) FROM ECOM_DB.GOLD.FCT_ORDER_ITEMS) AS gmv
    UNION ALL SELECT 'daily', (SELECT SUM(gmv) FROM ECOM_DB.GOLD.MART_DAILY_REVENUE)
    UNION ALL SELECT 'category', (SELECT SUM(gmv) FROM ECOM_DB.GOLD.MART_CATEGORY_MONTHLY)
    UNION ALL SELECT 'customer', (SELECT SUM(lifetime_gmv) FROM ECOM_DB.GOLD.DIM_CUSTOMER)
)
SELECT COUNT(*) AS checked_count, COUNT_IF(c.gmv IS DISTINCT FROM o.gmv) AS failing_count
FROM c CROSS JOIN o